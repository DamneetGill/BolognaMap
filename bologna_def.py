    elev_u = G.nodes[u].get("elev", 0)
    elev_v = G.nodes[v].get("elev", 0)

    # 3. Gestione pendenza e dislivello
    if elev_u == 0 or elev_v == 0:
        slope_pct = 0
        delta_h = 0
    else:
        delta_h = abs(elev_v - elev_u)
        slope_pct = (delta_h / length) * 100

    # nodo Way
    G.add_node(
        way_id,
        type="Way",
        mode=data.get("mode", "unknown"),
        portico=data.get("portico", 0),
        geometry=geom,
        avg_elev=(elev_u + elev_v) / 2, # Altitudine media
        delta_h=delta_h,                # Dislivello totale
        slope_pct=slope_pct,             # Pendenza percentuale
        length = length         # Lunghezza in metri della strada
    )

    # Collega i nodi fisici al nodo Way
    G.add_edge(u, way_id, type="MEMBER_OF")
    G.add_edge(v, way_id, type="MEMBER_OF")

