# 1. Legge transform dal file .tfw


def read_tfw(tfw_path):
    with open(tfw_path, "r") as f:
        A = float(f.readline())  # pixel size X
        D = float(f.readline())  # rotation
        B = float(f.readline())  # rotation
        E = float(f.readline())  # pixel size Y (negative)
        C = float(f.readline())  # top left X
        F = float(f.readline())  # top left Y

    return Affine(A, B, C, D, E, F)


# 2. Legge CRS dal file .prj


def read_prj(prj_path):
    with open(prj_path, "r") as f:
        wkt = f.read()
    return CRS.from_wkt(wkt)


# 3. Carica tutti i raster con georeferencing


def load_rasters(folder):

    raster_files = glob.glob(os.path.join(folder, "*.tif"))

    rasters = []

    for tif_path in raster_files:

        base = os.path.splitext(tif_path)[0]

        tfw_path = base + ".tfw"
        prj_path = base + ".prj"

        if not os.path.exists(tfw_path):
            print(f"TFW mancante per {tif_path}")
            continue

        if not os.path.exists(prj_path):
            print(f"PRJ mancante per {tif_path}")
            continue

        transform = read_tfw(tfw_path)
        crs = read_prj(prj_path)

        ds = rasterio.open(tif_path)

        bounds = rasterio.transform.array_bounds(
            ds.height,
            ds.width,
            transform
        )

        rasters.append({
            "dataset": ds,
            "transform": transform,
            "bounds": bounds,
            "crs": crs
        })

    print(f"Caricati {len(rasters)} raster correttamente")

    return rasters


# 4. Estrae elevazione da coordinate lon/lat


def get_elevation(lon, lat, rasters):

    for r in rasters:

        left, bottom, right, top = r["bounds"]

        if left <= lon <= right and bottom <= lat <= top:

            transform = r["transform"]

            col, row = ~transform * (lon, lat)

            col = int(col)
            row = int(row)

            ds = r["dataset"]

            if 0 <= row < ds.height and 0 <= col < ds.width:

                elevation = ds.read(1)[row, col]

                if elevation < -1000:
                    return 0

                return float(elevation)

    return 0



# 5. Aggiorna grafo NetworkX


def add_elevation_to_graph(G, raster_folder):
    rasters = load_rasters(raster_folder)

    graph_crs = "EPSG:3857"


    transformers = {}
    for i, r in enumerate(rasters):
        target_crs = r["crs"]
        transformers[i] = Transformer.from_crs(graph_crs, target_crs, always_xy=True)

    count = 0
    for node_id, data in G.nodes(data=True):
        geom = data.get("geometry")

        if geom is None:
          continue

        x = geom.x
        y = geom.y

        if x is None or y is None:
            continue

        elev = 0
        for i, r in enumerate(rasters):

            lon_r, lat_r = transformers[i].transform(x, y)

            left, bottom, right, top = r["bounds"]
            if left <= lon_r <= right and bottom <= lat_r <= top:
                transform = r["transform"]
                col, row = ~transform * (lon_r, lat_r)
                col, row = int(col), int(row)

                ds = r["dataset"]
                if 0 <= row < ds.height and 0 <= col < ds.width:
             
                    window = rasterio.windows.Window(col, row, 1, 1)
                    val = ds.read(1, window=window)
                    elev = float(val[0, 0])

                    if elev < -1000: 
                        elev = 0
                    break
        G.nodes[node_id]["elev"] = elev
        count += 1

    print(f"Aggiornati {count} nodi con elevazione")
    return G
