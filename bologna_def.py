def get_predominant_mask(network_gdf, original_lines_gdf, threshold=0.5):
    """
    Ritorna una maschera booleana per i segmenti che si sovrappongono
    significativamente alle linee originali.
    """
    # 1. Creiamo un piccolo buffer attorno alle linee originali (es. 0.5 metri)
    # per compensare piccoli errori di precisione numerica dello snap
    original_buffer = original_lines_gdf.buffer(0.5)
    union_buffer = original_buffer.union_all()

    # 2. Calcoliamo l'intersezione spaziale tra la rete e il buffer
    # intersection() calcola la parte di geometria comune
    intersections = network_gdf.geometry.intersection(union_buffer)

    # 3. Calcoliamo la percentuale di copertura
    # Se la lunghezza dell'intersezione / lunghezza totale > soglia -> True
    coverage_ratio = intersections.length / network_gdf.geometry.length

    return coverage_ratio > threshold

